export type AgentStatus =
  | 'ONLINE'
  | 'WORKING'
  | 'READING'
  | 'TESTING'
  | 'WAITING'
  | 'IDLE'
  | 'DONE'
  | 'OFFLINE';

export type ActivityType =
  | 'REGISTERED'
  | 'INTENT'
  | 'READING'
  | 'FOUND'
  | 'CHANGED'
  | 'CREATED'
  | 'TESTING'
  | 'WAITING'
  | 'DONE'
  | 'NOTE'
  | 'HEARTBEAT'
  | 'UNREGISTERED'
  | 'OBSERVED'
  | 'MESSAGE'
  | 'TASK';

export interface CodePointer {
  file: string;
  symbol?: string;
  parameter?: string;
}

export interface AgentState {
  id: string;
  role?: string;
  sessionId: string;
  status: AgentStatus;
  task?: string;
  current?: {
    type: ActivityType;
    description: string;
    pointer?: CodePointer;
    reason?: string;
    waitingFor?: string;
  };
  startedAt: string;
  updatedAt: string;
  lastHeartbeatAt: string;
}

export interface AgentActivity {
  id: string;
  agentId: string;
  type: ActivityType;
  task?: string;
  pointer?: CodePointer;
  description: string;
  reason?: string;
  waitingFor?: string;
  timestamp: string;
}

export interface AgentMessage {
  id: string;
  from: string;
  to: string;
  body: string;
  pointer?: CodePointer;
  /** `waiting` is generated by the system when an agent declares a dependency. */
  kind: 'direct' | 'waiting' | 'task';
  timestamp: string;
}

export type TaskStatus = 'OPEN' | 'CLAIMED' | 'DONE' | 'FAILED' | 'CANCELLED';

export interface AgentTask {
  id: string;
  title: string;
  detail?: string;
  pointer?: CodePointer;
  createdBy: string;
  /** When set, only this agent may claim the task. */
  assignedTo?: string;
  status: TaskStatus;
  claimedBy?: string;
  claimedAt?: string;
  /** A claim past this instant is returned to the pool, so a dead runner blocks nothing. */
  claimExpiresAt?: string;
  finishedAt?: string;
  result?: string;
  attempts: number;
  /** How many spawn generations deep this task is; bounded to stop runaway recursion. */
  depth: number;
  parentTaskId?: string;
  scheduleId?: string;
  /**
   * Not claimable until every one of these reaches DONE. Accepts a bare string for tasks
   * written before it took a list.
   */
  dependsOn?: string | string[];
  /** Set on a review task: the id of the work it judges. */
  reviewOf?: string;
  /** Set on a work task: the id of the review that must accept it. */
  reviewTaskId?: string;
  /** Set on a work task: how many times a review has sent it back. */
  reviewRounds?: number;
  createdAt: string;
  updatedAt: string;
}

export interface TaskSchedule {
  id: string;
  cron: string;
  title: string;
  detail?: string;
  pointer?: CodePointer;
  assignedTo?: string;
  enabled: boolean;
  createdBy: string;
  lastRunAt?: string;
  nextRunAt?: string;
  createdAt: string;
  updatedAt: string;
}

export interface Conflict {
  agentId: string;
  status: AgentStatus;
  task?: string;
  pointer: CodePointer;
  description: string;
  exact: boolean;
}

export interface ProjectConfig {
  version: 1;
  staleAfterSeconds: number;
  recentHistoryLimit: number;
  projectName: string;
  /**
   * Archive the journal once it passes this many events. 0 disables it, leaving the
   * journal to grow until someone runs `compact`.
   */
  autoCompactAfterEvents: number;
  /** How long a claim is held before it returns to the pool. */
  taskClaimSeconds: number;
  /** Maximum spawn generations: a task created while running a task is one deeper. */
  maxTaskDepth: number;
  /**
   * How many expired claims a task may collect before it is treated as poisonous and
   * failed instead of returned to the queue. 0 disables the dead letter.
   */
  maxTaskAttempts: number;
  /**
   * How many times a review may reject the same work before it is failed for a human
   * instead of requeued. Two agents that disagree would otherwise trade rejections
   * forever, spending real money on every round. 0 disables the limit.
   */
  maxReviewRounds: number;
}
