export type AgentStatus =
  | 'ONLINE'
  | 'WORKING'
  | 'READING'
  | 'TESTING'
  | 'WAITING'
  | 'IDLE'
  | 'DONE'
  | 'OFFLINE';

export type ActivityType =
  | 'REGISTERED'
  | 'INTENT'
  | 'READING'
  | 'FOUND'
  | 'CHANGED'
  | 'CREATED'
  | 'TESTING'
  | 'WAITING'
  | 'DONE'
  | 'NOTE'
  | 'HEARTBEAT'
  | 'UNREGISTERED'
  | 'OBSERVED'
  | 'MESSAGE';

export interface CodePointer {
  file: string;
  symbol?: string;
  parameter?: string;
}

export interface AgentState {
  id: string;
  role?: string;
  sessionId: string;
  status: AgentStatus;
  task?: string;
  current?: {
    type: ActivityType;
    description: string;
    pointer?: CodePointer;
    reason?: string;
    waitingFor?: string;
  };
  startedAt: string;
  updatedAt: string;
  lastHeartbeatAt: string;
}

export interface AgentActivity {
  id: string;
  agentId: string;
  type: ActivityType;
  task?: string;
  pointer?: CodePointer;
  description: string;
  reason?: string;
  waitingFor?: string;
  timestamp: string;
}

export interface AgentMessage {
  id: string;
  from: string;
  to: string;
  body: string;
  pointer?: CodePointer;
  /** `waiting` is generated by the system when an agent declares a dependency. */
  kind: 'direct' | 'waiting';
  timestamp: string;
}

export interface Conflict {
  agentId: string;
  status: AgentStatus;
  task?: string;
  pointer: CodePointer;
  description: string;
  exact: boolean;
}

export interface ProjectConfig {
  version: 1;
  staleAfterSeconds: number;
  recentHistoryLimit: number;
  projectName: string;
}
