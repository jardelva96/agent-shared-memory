import { AgentActivity, AgentState, ProjectConfig } from '../models/types.js';
import { ageSeconds, localTime } from '../utils/time.js';
import { formatPointer } from './pointer.js';

export function effectiveStatus(state: AgentState, config: ProjectConfig): AgentState['status'] {
  if (state.status === 'DONE') return 'DONE';
  return ageSeconds(state.lastHeartbeatAt) > config.staleAfterSeconds ? 'OFFLINE' : state.status;
}

export function renderSharedMemory(
  states: AgentState[],
  recent: AgentActivity[],
  config: ProjectConfig
): string {
  const now = new Date().toISOString();
  const sorted = [...states].sort((a, b) => a.id.localeCompare(b.id));
  const lines: string[] = [
    '# SHARED AGENT MEMORY',
    '',
    `Project: ${config.projectName}`,
    `Updated: ${now}`,
    '',
    '> This file is generated automatically. Agents should use the CLI/API instead of editing it directly.',
    '',
    '## ACTIVE AGENTS',
    ''
  ];

  if (sorted.length === 0) {
    lines.push('_No agents registered._', '');
  }

  for (const state of sorted) {
    const status = effectiveStatus(state, config);
    lines.push(`### ${state.id} | ${status}${state.role ? ` | ${state.role}` : ''}`);
    lines.push(`Demand: ${state.task ?? '-'}`);
    lines.push(`Now: ${state.current?.description ?? 'No current action.'}`);
    lines.push(`Pointer: ${formatPointer(state.current?.pointer)}`);
    if (state.current?.waitingFor) lines.push(`Waiting for: ${state.current.waitingFor}`);
    lines.push(`Details: .agents/history/${state.id}.md`);
    lines.push(`Heartbeat: ${state.lastHeartbeatAt} (${ageSeconds(state.lastHeartbeatAt)}s ago)`);
    lines.push('');
  }

  lines.push('## RECENT CHANGES', '');
  if (recent.length === 0) {
    lines.push('_No recent activity._', '');
  } else {
    for (const activity of recent.slice(0, config.recentHistoryLimit)) {
      lines.push(
        `- ${localTime(activity.timestamp)} | ${activity.agentId} | ${activity.type} | ${activity.description}` +
          (activity.pointer ? ` | ${formatPointer(activity.pointer)}` : '')
      );
    }
    lines.push('');
  }

  lines.push('## PROTOCOL', '');
  lines.push('1. Read shared memory before a relevant code action.');
  lines.push('2. Announce INTENT before changing code.');
  lines.push('3. Register CHANGED/CREATED/TESTING/DONE immediately after the action.');
  lines.push('4. Use semantic pointers: `file::symbol::parameter`, not fragile line numbers.');
  lines.push('5. Never edit another agent\'s history file.');
  lines.push('');
  return `${lines.join('\n')}\n`;
}

export function renderAgentHeader(state: AgentState): string {
  return [
    `# ${state.id}`,
    '',
    `Role: ${state.role ?? '-'}`,
    `Session: ${state.sessionId}`,
    `Started: ${state.startedAt}`,
    '',
    '> Append-only operational journal generated by Agent Shared Memory.',
    ''
  ].join('\n');
}

/** Marks a new session inside a history file that already exists. */
export function renderSessionBanner(state: AgentState): string {
  return [
    '---',
    '',
    `## Session ${state.sessionId}`,
    '',
    `Role: ${state.role ?? '-'}`,
    `Started: ${state.startedAt}`,
    ''
  ].join('\n');
}

export function renderActivity(activity: AgentActivity): string {
  const lines = [
    '---',
    '',
    `## ${activity.timestamp} | ${activity.type}`,
    '',
    `Demand: ${activity.task ?? '-'}`,
    `Description: ${activity.description}`
  ];
  if (activity.pointer) lines.push(`Pointer: ${formatPointer(activity.pointer)}`);
  if (activity.reason) lines.push(`Reason: ${activity.reason}`);
  if (activity.waitingFor) lines.push(`Waiting for: ${activity.waitingFor}`);
  lines.push('');
  return lines.join('\n');
}
